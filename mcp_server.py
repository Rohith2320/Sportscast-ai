from fastmcp import FastMCP

mcp = FastMCP("SportsCast AI")


@mcp.tool()
def analyze_sport(sport: str, match_id: str, persona: str = "espn_formal") -> str:
    """Analyze a sports match and return broadcast-quality narrative.
    sport: nba, f1, soccer, valorant, or mlb
    match_id: team name like 'Knicks', 'latest', race name like 'monaco', or specific game ID
    persona: espn_formal or tactical_coach
    Returns full narrative analysis generated by 5-agent LangGraph pipeline."""
    from graph import run_analysis
    result = run_analysis(sport, match_id, persona)
    if result.get('error'):
        return f"Error: {result['error']}"
    return result.get('narrative', 'No narrative generated')


@mcp.tool()
def list_cached_analyses(sport: str = None) -> str:
    """List all cached sports analyses available in SportsCast AI.
    sport: optional filter — nba, f1, soccer, valorant, mlb, or None for all
    Returns list of available analyses with titles and dates."""
    from utils.cache import list_cached_games
    games = list_cached_games(sport)
    if not games:
        return f"No cached analyses found{' for ' + sport if sport else ''}."
    lines = [f"Found {len(games)} cached analyses:"]
    for g in games:
        lines.append(f"- {g['sport'].upper()}: {g.get('title', g['game_id'])} ({g.get('cached_at','')[:10]})")
    return "\n".join(lines)


@mcp.tool()
def chat_about_game(sport: str, game_id: str, question: str) -> str:
    """Ask a question about a specific analyzed game using the SportsCast AI chat agent.
    sport: nba, f1, soccer, valorant, or mlb
    game_id: the game ID (get from list_cached_analyses)
    question: any question about the game — why did they win, who performed best, etc.
    Returns AI analyst response with intent classification."""
    from utils.cache import load_from_cache
    from utils.cost_tracker import reset_session_cost
    cached = load_from_cache(game_id, sport)
    if not cached:
        return f"No analysis found for {sport} game {game_id}. Run analyze_sport first."
    try:
        reset_session_cost()
        from agents.chat_agent import (
            classify_intent, build_smart_context,
            generate_chat_response, extract_players_from_analysis,
            find_player_in_query
        )
        players = extract_players_from_analysis(cached.get('player_analysis', ''))
        intent = classify_intent(question, [])
        player_in_query = len(find_player_in_query(question, players)) > 0
        context = build_smart_context(question, cached, intent, players)
        response = generate_chat_response(
            question, context, [], intent,
            sport.upper(), players, player_in_query
        )
        return f"[{intent.upper()}] {response}"
    except Exception as e:
        return f"Chat error: {str(e)}"


@mcp.tool()
def discover_latest_game(sport: str) -> str:
    """Find the most recent available game for a sport without running analysis.
    sport: nba, f1, soccer, valorant, or mlb
    Returns match_id and display name to use with analyze_sport."""
    import requests
    try:
        r = requests.get(f'http://localhost:8000/discover/{sport}', timeout=15)
        data = r.json()
        return f"Latest {sport.upper()} game: {data.get('display_name', 'Unknown')} (match_id: {data.get('match_id', 'unknown')})"
    except Exception as e:
        return f"Could not discover latest {sport} game: {str(e)}"


if __name__ == "__main__":
    print("SportsCast AI MCP Server starting on port 8001...")
    print("Tools available: analyze_sport, list_cached_analyses, chat_about_game, discover_latest_game")
    mcp.run(transport="streamable-http", port=8001)
